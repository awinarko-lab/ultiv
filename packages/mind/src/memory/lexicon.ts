/** Concept token for a term (stable slug from the group's first entry). */
export const conceptToken = (term: string): string =>
  `§${term
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")}`;

/** term → concept token, built once. Longer terms win (multi-word phrases). */
export const CONCEPT_OF: ReadonlyMap<string, string> = (() => {
  const map = new Map<string, string>();
  for (const group of SYNONYM_GROUPS) {
    const token = conceptToken(group[0] ?? "");
    for (const term of group) {
      const normalized = term.trim().toLowerCase();
      const existing = map.get(normalized);
      if (existing === undefined || normalized.length > (existing.length ?? 0)) {
        if (existing === undefined || normalized.includes(" ")) map.set(normalized, token);
      }
    }
  }
  return map;
})();

